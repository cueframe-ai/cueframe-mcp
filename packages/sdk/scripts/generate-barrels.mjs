#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const sdkRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedRoot = join(sdkRoot, "src", "generated");
const zodRoot = join(generatedRoot, "zod");

function tagModules(root) {
  return readdirSync(root)
    .filter((entry) => statSync(join(root, entry)).isDirectory())
    .filter((entry) => entry !== "models" && entry !== "zod")
    .map((tag) => {
      const modulePath = join(root, tag, `${tag}.ts`);
      if (!existsSync(modulePath) || !statSync(modulePath).isFile()) {
        throw new Error(`generated tag '${tag}' has no ${tag}/${tag}.ts module`);
      }
      return tag;
    })
    .sort((a, b) => a.localeCompare(b));
}

function namespaceName(tag) {
  return tag.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
}

const operationTags = tagModules(generatedRoot);
const zodTags = tagModules(zodRoot);

writeFileSync(
  join(generatedRoot, "operations.ts"),
  [
    "/** Generated by packages/sdk/scripts/generate-barrels.mjs. Do not edit. */",
    ...operationTags.map(
      (tag) => `export * as ${namespaceName(tag)} from "./${tag}/${tag}";`,
    ),
    "",
  ].join("\n"),
);

writeFileSync(
  join(zodRoot, "index.ts"),
  [
    "/** Generated by packages/sdk/scripts/generate-barrels.mjs. Do not edit. */",
    ...zodTags.flatMap((tag) => {
      const path = `./${tag}/${tag}`;
      // Orval 8 names operation schemas in PascalCase. Preserve the SDK's
      // published camelCase exports while sharing the same schema instances.
      const source = readFileSync(join(zodRoot, tag, `${tag}.ts`), 'utf8');
      const names = [...source.matchAll(/export const ([A-Z][A-Za-z0-9_]*)\b/g)].map(match => match[1]);
      return [`export * from "${path}";`, ...names.map(name =>
        `export { ${name} as ${name[0].toLowerCase()}${name.slice(1)} } from "${path}";`)];
    }),
    "",
  ].join("\n"),
);

// The component execution versions the contract admits, as one generated constant: readers negotiate
// with it (componentExecutionVersions) instead of restating the list or walking schema internals.
const contract = JSON.parse(readFileSync(join(sdkRoot, "..", "api-contract", "dist", "openapi.json"), "utf8"));
const executionVersions = contract.components.schemas.ComponentExecutionRef.oneOf.map((arm) => arm.properties.version.const);
if (!executionVersions.length || !executionVersions.every(Number.isInteger)) {
  throw new Error(`ComponentExecutionRef declares no integer version consts: ${JSON.stringify(executionVersions)}`);
}
writeFileSync(
  join(generatedRoot, "executionVersions.ts"),
  `/** Generated by packages/sdk/scripts/generate-barrels.mjs from ComponentExecutionRef. Do not edit. */\nexport const COMPONENT_EXECUTION_VERSIONS = ${JSON.stringify(executionVersions)} as const;\n`,
);

console.log(
  `generated SDK barrels (${operationTags.length} operation tags, ${zodTags.length} zod tags)`,
);
